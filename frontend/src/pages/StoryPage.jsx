import { Download, FileCode2, Pencil, Plus, RefreshCw, Sparkles, Trash2, X } from 'lucide-react';
import { useState } from 'react';
import { useNavigate, useParams } from 'react-router-dom';
import Breadcrumbs from '../components/Breadcrumbs';
import CodeBlock from '../components/CodeBlock';
import StoryForm from '../components/forms/StoryForm';
import NotFoundState from '../components/NotFoundState';
import { TYPES } from '../components/testcases/constants';
import GeneratingAnimation from '../components/testcases/GeneratingAnimation';
import TestCaseForm from '../components/testcases/TestCaseForm';
import TestCaseTable from '../components/testcases/TestCaseTable';
import Banner from '../components/ui/Banner';
import Button from '../components/ui/Button';
import Card from '../components/ui/Card';
import ConfirmDialog from '../components/ui/ConfirmDialog';
import EmptyState from '../components/ui/EmptyState';
import { Input } from '../components/ui/Field';
import Modal from '../components/ui/Modal';
import Skeleton, { LoadingBlock } from '../components/ui/Skeleton';
import { useToast } from '../contexts/ToastContext';
import { useDocumentTitle } from '../hooks/useDocumentTitle';
import { useResource } from '../hooks/useResource';
import { api } from '../services/api';
import { cn } from '../services/cn';
import { plural } from '../services/format';

const PRIORITY_ORDER = { HIGH: 0, MEDIUM: 1, LOW: 2 };
const byPriorityThenId = (a, b) =>
  PRIORITY_ORDER[a.priority] - PRIORITY_ORDER[b.priority] || a.id - b.id;
const DEFAULT_BASE_URL = 'http://localhost:3000';

function FilterChips({ testCases, value, onChange }) {
  const options = ['ALL', ...TYPES];
  const count = (type) =>
    type === 'ALL' ? testCases.length : testCases.filter((tc) => tc.type === type).length;
  return (
    <div role="group" aria-label="Filter by type" className="flex flex-wrap gap-2">
      {options.map((type) => {
        const active = value === type;
        return (
          <button
            key={type}
            type="button"
            aria-pressed={active}
            onClick={() => onChange(type)}
            data-testid={`type-filter-${type}`}
            className={cn(
              'inline-flex items-center gap-2 rounded-full border px-3.5 py-1.5 text-sm font-medium transition',
              active
                ? 'border-transparent bg-fg text-bg shadow-card'
                : 'border-line bg-surface text-muted hover:border-accent/40 hover:text-fg',
            )}
          >
            {type === 'ALL' ? 'All' : type.charAt(0) + type.slice(1).toLowerCase()}
            <span
              className={cn(
                'rounded-full px-1.5 text-xs tabular-nums',
                active ? 'bg-bg/20 text-bg' : 'bg-surface-2 text-muted',
              )}
            >
              {count(type)}
            </span>
          </button>
        );
      })}
    </div>
  );
}

function slugify(text) {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'story'
  );
}

function PlaywrightPanel({ story, result, loading, onGenerate, onClose }) {
  const [baseUrl, setBaseUrl] = useState(result?.baseUrl ?? DEFAULT_BASE_URL);
  return (
    <section aria-labelledby="playwright-heading" className="space-y-4">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <h2 id="playwright-heading" className="flex items-center gap-2 text-xl font-semibold">
            <FileCode2 className="size-5 text-accent-fg" aria-hidden="true" /> Playwright script
          </h2>
          <p className="text-sm text-muted">
            One <code className="font-mono text-xs">test()</code> per test case, using role and
            label locators.
            {result && (
              <>
                {' '}
                Generated by <span className="font-mono text-xs">{result.model}</span>.
              </>
            )}
          </p>
        </div>
        <div className="flex items-end gap-2">
          <form
            className="flex flex-wrap items-end gap-2"
            onSubmit={(event) => {
              event.preventDefault();
              onGenerate(baseUrl.trim());
            }}
          >
            <Input
              label="Base URL"
              value={baseUrl}
              onChange={(event) => setBaseUrl(event.target.value)}
              inputClassName="h-9 w-full sm:w-56"
              type="url"
            />
            <Button type="submit" variant="secondary" size="md" icon={RefreshCw} loading={loading}>
              Regenerate
            </Button>
          </form>
          <Button
            variant="ghost"
            size="icon"
            onClick={onClose}
            aria-label="Close Playwright script"
          >
            <X className="size-4" aria-hidden="true" />
          </Button>
        </div>
      </div>
      {loading && !result ? (
        <LoadingBlock label="Generating Playwright script">
          <Skeleton className="h-72 rounded-2xl" />
        </LoadingBlock>
      ) : (
        result && (
          <CodeBlock
            code={result.script}
            filename={`${slugify(story.title)}.spec.js`}
            testId="playwright-script"
          />
        )
      )}
    </section>
  );
}

export default function StoryPage() {
  const { storyId } = useParams();
  const navigate = useNavigate();
  const toast = useToast();
  const { data, error, reload, setData } = useResource(
    async (signal) => {
      const [loadedStory, cases] = await Promise.all([
        api.stories.get(storyId, signal),
        api.testCases.list(storyId, signal),
      ]);
      const project = await api.projects.get(loadedStory.projectId, signal);
      return [loadedStory, cases, project];
    },
    [storyId],
  );
  const [story, testCases, project] = data ?? [];
  useDocumentTitle(story?.title ?? 'Story');

  const [filter, setFilter] = useState('ALL');
  const [generating, setGenerating] = useState(false);
  const [generationError, setGenerationError] = useState(null);
  const [animateRows, setAnimateRows] = useState(false);
  const [playwright, setPlaywright] = useState({ open: false, loading: false, result: null });
  const [exporting, setExporting] = useState(false);
  const [dialog, setDialog] = useState(null); // { kind: 'edit-story' | 'delete-story' | 'add-case' | 'edit-case' | 'delete-case', testCase? }
  const close = () => setDialog(null);

  if (error?.status === 404 || error?.status === 400) return <NotFoundState what="story" />;

  const setTestCases = (update) =>
    setData(([currentStory, current, currentProject]) => [
      currentStory,
      update(current),
      currentProject,
    ]);

  const generate = async () => {
    setGenerating(true);
    setGenerationError(null);
    try {
      const result = await api.ai.generate(storyId);
      setTestCases(() => result.testCases);
      setAnimateRows(true);
      setFilter('ALL');
      setPlaywright((current) => ({ ...current, result: null, open: false }));
      const aiCount = result.testCases.filter((tc) => tc.source === 'AI').length;
      toast.success(`Generated ${plural(aiCount, 'test case')} with ${result.model}`);
    } catch (err) {
      setGenerationError(err.message);
    } finally {
      setGenerating(false);
    }
  };

  const generatePlaywright = async (baseUrl = DEFAULT_BASE_URL) => {
    setPlaywright((current) => ({ ...current, open: true, loading: true }));
    try {
      const result = await api.ai.playwright(storyId, baseUrl);
      setPlaywright({ open: true, loading: false, result: { ...result, baseUrl } });
    } catch (err) {
      setPlaywright((current) => ({ ...current, loading: false, open: Boolean(current.result) }));
      toast.error(err.message);
    }
  };

  const exportExcel = async () => {
    setExporting(true);
    try {
      const filename = await api.exportExcel(storyId);
      toast.success(`Downloaded ${filename}`);
    } catch (err) {
      toast.error(err.message);
    } finally {
      setExporting(false);
    }
  };

  const saveStory = async (values) => {
    const updated = await api.stories.update(storyId, values);
    setData(([, current, currentProject]) => [updated, current, currentProject]);
    close();
    toast.success('Story updated');
  };

  const deleteStory = async () => {
    try {
      await api.stories.remove(storyId);
      toast.success('Story deleted');
      navigate(`/projects/${story.projectId}`, { replace: true });
    } catch (err) {
      close();
      toast.error(err.message);
    }
  };

  const addTestCase = async (values) => {
    const created = await api.testCases.create(storyId, values);
    setTestCases((current) => [...current, created].sort(byPriorityThenId));
    setAnimateRows(false);
    close();
    toast.success('Test case added');
  };

  const updateTestCase = async (values) => {
    const updated = await api.testCases.update(dialog.testCase.id, values);
    setTestCases((current) =>
      current.map((tc) => (tc.id === updated.id ? updated : tc)).sort(byPriorityThenId),
    );
    close();
    toast.success('Test case updated');
  };

  // Optimistic: the row disappears at once and comes back if the server refuses.
  const deleteTestCase = async () => {
    const removed = dialog.testCase;
    setTestCases((current) => current.filter((tc) => tc.id !== removed.id));
    close();
    try {
      await api.testCases.remove(removed.id);
      toast.success('Test case deleted');
    } catch (err) {
      setTestCases((current) => [...current, removed].sort(byPriorityThenId));
      toast.error(err.message);
    }
  };

  const visible = testCases?.filter((tc) => filter === 'ALL' || tc.type === filter) ?? [];
  const hasCases = testCases?.length > 0;
  const hasAiCases = testCases?.some((tc) => tc.source === 'AI');

  return (
    <div>
      <Breadcrumbs
        items={[
          { label: 'Dashboard', to: '/' },
          {
            label: project?.name ?? 'Project',
            to: story ? `/projects/${story.projectId}` : undefined,
          },
          { label: story?.title ?? 'Story' },
        ]}
      />

      {error && !data && (
        <Banner
          title="Could not load this story"
          action={
            <Button variant="secondary" size="sm" icon={RefreshCw} onClick={reload}>
              Try again
            </Button>
          }
        >
          {error.message}
        </Banner>
      )}

      {!data && !error && (
        <LoadingBlock label="Loading story" className="space-y-4">
          <Skeleton className="h-56 rounded-2xl" />
          <Skeleton className="h-12 w-2/3 rounded-xl" />
          <Skeleton className="h-64 rounded-2xl" />
        </LoadingBlock>
      )}

      {data && (
        <div className="space-y-8">
          <Card className="relative overflow-hidden">
            <div
              className="bg-glow pointer-events-none absolute inset-0 opacity-60"
              aria-hidden="true"
            />
            <div className="relative p-6 sm:p-8">
              <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
                <div className="min-w-0">
                  <p className="text-sm font-medium text-accent-fg">User story</p>
                  <h1 className="mt-1 text-3xl font-semibold break-words">{story.title}</h1>
                </div>
                <div className="flex shrink-0 gap-2">
                  <Button
                    variant="secondary"
                    icon={Pencil}
                    onClick={() => setDialog({ kind: 'edit-story' })}
                    data-testid="story-edit"
                  >
                    Edit
                  </Button>
                  <Button
                    variant="danger-ghost"
                    icon={Trash2}
                    onClick={() => setDialog({ kind: 'delete-story' })}
                    data-testid="story-delete"
                  >
                    Delete
                  </Button>
                </div>
              </div>
              <div className="mt-5 grid gap-6 lg:grid-cols-2">
                <div>
                  <h2 className="text-xs font-semibold tracking-wider text-subtle uppercase">
                    Description
                  </h2>
                  <p className="mt-2 leading-relaxed whitespace-pre-line text-fg">
                    {story.description}
                  </p>
                </div>
                <div>
                  <h2 className="text-xs font-semibold tracking-wider text-subtle uppercase">
                    Acceptance criteria
                  </h2>
                  {story.acceptanceCriteria ? (
                    <ul className="mt-2 space-y-1.5">
                      {story.acceptanceCriteria
                        .split('\n')
                        .filter((line) => line.trim())
                        .map((line, index) => (
                          <li key={index} className="flex gap-2 text-fg">
                            <span
                              className="mt-2 size-1.5 shrink-0 rounded-full bg-accent"
                              aria-hidden="true"
                            />
                            {line.replace(/^[-*•]\s*/, '')}
                          </li>
                        ))}
                    </ul>
                  ) : (
                    <p className="mt-2 text-muted">
                      None yet. Adding criteria helps the AI find edge cases.
                    </p>
                  )}
                </div>
              </div>
              <div className="mt-6 flex flex-col gap-3 border-t border-line pt-6 sm:flex-row sm:items-center">
                <Button
                  size="lg"
                  icon={Sparkles}
                  onClick={generate}
                  loading={generating}
                  data-testid="generate-button"
                >
                  {generating
                    ? 'Generating…'
                    : hasAiCases
                      ? 'Regenerate test cases'
                      : 'Generate test cases'}
                </Button>
                <p className="text-sm text-muted">
                  {hasAiCases
                    ? 'Regenerating replaces AI cases. Your manual cases are kept.'
                    : 'Claude writes positive, negative and edge cases from this story.'}
                </p>
              </div>
            </div>
          </Card>

          {generationError && (
            <Banner
              title="Generation failed"
              data-testid="generation-error"
              onDismiss={() => setGenerationError(null)}
              action={
                <Button variant="secondary" size="sm" icon={RefreshCw} onClick={generate}>
                  Try again
                </Button>
              }
            >
              {generationError} Your existing test cases were not changed.
            </Banner>
          )}

          <section aria-labelledby="test-cases-heading" className="space-y-4">
            <div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
              <div>
                <h2 id="test-cases-heading" className="text-xl font-semibold">
                  Test cases
                </h2>
                <p className="text-sm text-muted">
                  {plural(testCases.length, 'test case')} · ordered by priority
                </p>
              </div>
              <div className="flex flex-wrap gap-2">
                <Button
                  variant="secondary"
                  icon={Plus}
                  onClick={() => setDialog({ kind: 'add-case' })}
                  data-testid="add-test-case-button"
                >
                  Add test case
                </Button>
                <Button
                  variant="secondary"
                  icon={Download}
                  onClick={exportExcel}
                  loading={exporting}
                  disabled={!hasCases}
                  data-testid="export-button"
                >
                  Export Excel
                </Button>
                <Button
                  variant="secondary"
                  icon={FileCode2}
                  onClick={() => generatePlaywright(playwright.result?.baseUrl)}
                  loading={playwright.loading}
                  disabled={!hasCases}
                  data-testid="playwright-button"
                >
                  Generate Playwright
                </Button>
              </div>
            </div>

            {hasCases && !generating && (
              <FilterChips testCases={testCases} value={filter} onChange={setFilter} />
            )}

            {generating ? (
              <GeneratingAnimation />
            ) : !hasCases ? (
              <EmptyState
                title="No test cases yet"
                description="Generate them with AI in seconds, or write one yourself."
                action={
                  <div className="flex flex-wrap justify-center gap-2">
                    <Button icon={Sparkles} onClick={generate}>
                      Generate with AI
                    </Button>
                    <Button
                      variant="secondary"
                      icon={Plus}
                      onClick={() => setDialog({ kind: 'add-case' })}
                    >
                      Add manually
                    </Button>
                  </div>
                }
              />
            ) : visible.length === 0 ? (
              <p className="rounded-2xl border border-dashed border-line px-6 py-10 text-center text-sm text-muted">
                No {filter.toLowerCase()} test cases.
              </p>
            ) : (
              <TestCaseTable
                testCases={visible}
                animate={animateRows}
                onEdit={(testCase) => setDialog({ kind: 'edit-case', testCase })}
                onDelete={(testCase) => setDialog({ kind: 'delete-case', testCase })}
              />
            )}
          </section>

          {playwright.open && (
            <PlaywrightPanel
              key={playwright.result?.runId ?? 'new'}
              story={story}
              result={playwright.result}
              loading={playwright.loading}
              onGenerate={generatePlaywright}
              onClose={() => setPlaywright({ open: false, loading: false, result: null })}
            />
          )}

          <Modal open={dialog?.kind === 'edit-story'} onClose={close} title="Edit story" size="lg">
            <StoryForm story={story} onSubmit={saveStory} onCancel={close} />
          </Modal>
          <Modal
            open={dialog?.kind === 'add-case'}
            onClose={close}
            title="Add test case"
            description="Manual cases are kept when you regenerate with AI."
            size="lg"
          >
            <TestCaseForm onSubmit={addTestCase} onCancel={close} />
          </Modal>
          <Modal
            open={dialog?.kind === 'edit-case'}
            onClose={close}
            title="Edit test case"
            size="lg"
          >
            {dialog?.testCase && (
              <TestCaseForm testCase={dialog.testCase} onSubmit={updateTestCase} onCancel={close} />
            )}
          </Modal>
          <ConfirmDialog
            open={dialog?.kind === 'delete-story'}
            onClose={close}
            onConfirm={deleteStory}
            title="Delete story?"
            message={`"${story.title}" and its ${plural(testCases.length, 'test case')} will be permanently deleted.`}
            confirmLabel="Delete story"
          />
          <ConfirmDialog
            open={dialog?.kind === 'delete-case'}
            onClose={close}
            onConfirm={deleteTestCase}
            title="Delete test case?"
            message={
              dialog?.testCase ? `"${dialog.testCase.title}" will be permanently deleted.` : ''
            }
          />
        </div>
      )}
    </div>
  );
}
